// ── State ───────────────────────────────────────────────────

let allVessels = [];
let vesselMarkers = {};

// ── Load Data ───────────────────────────────────────────────

async function loadData() {
    try {
        const resp = await fetch(DATA_URL);
        if (!resp.ok) throw new Error("vessels.json not found");
        const data = await resp.json();
        allVessels = data.vessels || [];
    } catch (e) {
        console.warn("Could not load vessels.json, using demo data:", e.message);
        allVessels = generateDemoVessels();
    }

    // Load signal data
    try {
        const sigResp = await fetch(SIGNAL_URL);
        if (sigResp.ok) {
            const signal = await sigResp.json();
            updateSignalPanel(signal);
        }
    } catch (e) {
        console.warn("Could not load signal JSON:", e.message);
    }

    renderVessels();
    updateStats();
    renderVesselList();
}

function generateDemoVessels() {
    // Generate realistic demo data if pipeline hasn't been run yet
    const names = [
        "SORMOVSKIY 49", "ABYSS VOYAGER", "DARK HORIZON", "PHANTOM TIDE",
        "SHADOW MONARCH", "CRIMSON WAVE", "GHOST RUNNER", "IRON MAIDEN II",
        "STEEL SERPENT", "NIGHT CRAWLER", "BLACK PEARL", "VOID DANCER",
        "STORM HERALD", "ROGUE EMPRESS", "DARK FRONTIER", "SILENT PREDATOR",
        "OCEAN WRAITH", "STEEL GHOST", "PHANTOM CARGO", "IRON DRIFTER",
    ];
    const positions = generateDemoPositions(names.length);
    return names.map((name, i) => ({
        imo: `${9100000 + i * 1234}`,
        name,
        gfw_match: Math.random() > 0.2,
        identity_changes: Math.floor(Math.random() * 5),
        encounters: Math.floor(Math.random() * 10),
        risk_score: Math.floor(30 + Math.random() * 70),
        cargo_status: ["LOADED", "BALLAST", "UNKNOWN"][Math.floor(Math.random() * 3)],
        cargo_confidence: parseFloat((0.5 + Math.random() * 0.5).toFixed(2)),
        draft_m: parseFloat((5 + Math.random() * 15).toFixed(1)),
        speed_knots: parseFloat((8 + Math.random() * 8).toFixed(1)),
        est_cargo_barrels: [200000, 350000, 500000, 700000, 1400000][Math.floor(Math.random() * 5)],
        est_cargo_value_usd: 0,
        est_annual_flow_usd: 0,
        _lat: positions[i].lat,
        _lng: positions[i].lng,
    })).map(v => {
        v.est_cargo_value_usd = v.est_cargo_barrels * 78.5;
        v.est_annual_flow_usd = v.est_cargo_barrels * Math.max(v.encounters, 4) * 78.5;
        return v;
    });
}

// ── Render Vessels on Map ───────────────────────────────────

function renderVessels() {
    vesselLayer.clearLayers();
    vesselMarkers = {};

    const positions = allVessels.some(v => v._lat)
        ? null
        : generateDemoPositions(allVessels.length);

    allVessels.forEach((vessel, i) => {
        const lat = vessel._lat || (positions ? positions[i].lat : 0);
        const lng = vessel._lng || (positions ? positions[i].lng : 0);

        // Store position on vessel for later use
        vessel._lat = lat;
        vessel._lng = lng;

        const rc = riskClass(vessel.risk_score);
        const marker = L.marker([lat, lng], {
            icon: L.divIcon({
                className: `vessel-marker ${rc}`,
                iconSize: [14, 14],
                iconAnchor: [7, 7],
            }),
            zIndexOffset: vessel.risk_score * 10,
        });

        // Tooltip
        const cargoTag = vessel.cargo_status || "UNKNOWN";
        marker.bindTooltip(
            `<b>${vessel.name}</b><br>` +
            `IMO: ${vessel.imo}<br>` +
            `Risk: ${vessel.risk_score} | Cargo: ${cargoTag}<br>` +
            `Value: ${formatUSD(vessel.est_cargo_value_usd || 0)}`,
            { className: "vessel-tooltip", direction: "top", offset: [0, -10] }
        );

        marker.on("click", () => showVesselDetail(vessel));
        vesselLayer.addLayer(marker);
        vesselMarkers[vessel.imo] = marker;
    });
}

// ── Encounter Lines ─────────────────────────────────────────

function renderEncounters() {
    encounterLayer.clearLayers();
    // Draw lines between high-risk vessels that are close together (simulated STS)
    const highRisk = allVessels.filter(v => v.risk_score >= 60 && v.encounters > 0);
    for (let i = 0; i < highRisk.length; i++) {
        for (let j = i + 1; j < highRisk.length; j++) {
            const a = highRisk[i], b = highRisk[j];
            const dist = Math.sqrt(Math.pow(a._lat - b._lat, 2) + Math.pow(a._lng - b._lng, 2));
            if (dist < 5) { // within ~5 degrees
                const line = L.polyline(
                    [[a._lat, a._lng], [b._lat, b._lng]],
                    { color: "#a78bfa", weight: 1.5, dashArray: "4, 6", opacity: 0.6 }
                );
                line.bindTooltip(`⚠️ Potential STS: ${a.name} ↔ ${b.name}`, { sticky: true });
                encounterLayer.addLayer(line);
            }
        }
    }
}

// ── Stats Bar ───────────────────────────────────────────────

function updateStats() {
    document.getElementById("stat-total").textContent = allVessels.length;
    document.getElementById("stat-highrisk").textContent =
        allVessels.filter(v => v.risk_score >= 70).length;
    document.getElementById("stat-loaded").textContent =
        allVessels.filter(v => v.cargo_status === "LOADED").length;

    const activeCargoValue = allVessels
        .filter(v => v.cargo_status === "LOADED" && v.risk_score >= 70)
        .reduce((sum, v) => sum + (v.est_cargo_value_usd || 0), 0);
    document.getElementById("stat-cargo-value").textContent = formatUSD(activeCargoValue);
}

// ── Signal Panel ────────────────────────────────────────────

function updateSignalPanel(signal) {
    if (!signal) {
        // Compute from vessel data
        signal = computeSignalFromVessels();
    }

    document.getElementById("sig-brent").textContent = "$" + (signal.brent_crude_usd || 78.5).toFixed(2);
    document.getElementById("sig-fleet").textContent = signal.high_risk_vessels || "—";
    document.getElementById("sig-loadratio").textContent =
        `${signal.vessels_loaded || 0} / ${signal.vessels_ballast || 0}`;
    document.getElementById("sig-annual").textContent =
        formatUSD(signal.est_annual_sanctioned_flow_usd || 0);
    document.getElementById("sig-active").textContent =
        formatUSD(signal.est_active_cargo_value_usd || 0);

    // Risk tier overlay
    const tierEl = document.getElementById("tier-value");
    tierEl.textContent = signal.risk_tier || "—";
    tierEl.className = "tier-value tier-" + (signal.risk_tier || "MODERATE");
    document.getElementById("tier-flow").textContent =
        formatUSD(signal.est_annual_sanctioned_flow_usd || 0) + " / year";
}

function computeSignalFromVessels() {
    const highRisk = allVessels.filter(v => v.risk_score >= 70);
    const loaded = highRisk.filter(v => v.cargo_status === "LOADED").length;
    const ballast = highRisk.filter(v => v.cargo_status === "BALLAST").length;
    const totalAnnual = highRisk.reduce((s, v) => s + (v.est_annual_flow_usd || 0), 0);
    const activeCargo = highRisk
        .filter(v => v.cargo_status === "LOADED")
        .reduce((s, v) => s + (v.est_cargo_value_usd || 0), 0);

    return {
        brent_crude_usd: 78.5,
        high_risk_vessels: highRisk.length,
        vessels_loaded: loaded,
        vessels_ballast: ballast,
        est_annual_sanctioned_flow_usd: totalAnnual,
        est_active_cargo_value_usd: activeCargo,
        risk_tier: totalAnnual > 5e9 ? "CRITICAL" : totalAnnual > 1e9 ? "HIGH" : totalAnnual > 5e8 ? "ELEVATED" : "MODERATE",
    };
}

// ── Vessel Detail ───────────────────────────────────────────

function showVesselDetail(vessel) {
    document.getElementById("panel-signal").style.display = "none";
    document.getElementById("panel-vessel").style.display = "block";

    document.getElementById("vessel-name").textContent = vessel.name;
    document.getElementById("vessel-imo").textContent = "IMO: " + vessel.imo;

    const scoreEl = document.getElementById("vessel-risk-score");
    scoreEl.textContent = vessel.risk_score;

    const badge = document.getElementById("vessel-risk-badge");
    badge.className = "risk-badge-large " + riskClass(vessel.risk_score);

    // Cargo status
    const statusEl = document.getElementById("vessel-cargo-status");
    statusEl.textContent = vessel.cargo_status || "UNKNOWN";
    statusEl.className = "detail-value status-" + (vessel.cargo_status || "UNKNOWN");

    document.getElementById("vessel-cargo-conf").textContent =
        vessel.cargo_confidence != null ? (vessel.cargo_confidence * 100).toFixed(0) + "%" : "—";
    document.getElementById("vessel-draft").textContent =
        vessel.draft_m != null ? vessel.draft_m.toFixed(1) + " m" : "—";
    document.getElementById("vessel-speed").textContent =
        vessel.speed_knots != null ? vessel.speed_knots.toFixed(1) + " kn" : "—";
    document.getElementById("vessel-id-changes").textContent =
        vessel.identity_changes != null ? vessel.identity_changes : "—";
    document.getElementById("vessel-encounters").textContent =
        vessel.encounters != null ? vessel.encounters : "—";

    // Economic
    document.getElementById("vessel-barrels").textContent =
        formatNumber(vessel.est_cargo_barrels) + " bbl";
    document.getElementById("vessel-cargo-val").textContent =
        formatUSD(vessel.est_cargo_value_usd || 0);
    document.getElementById("vessel-annual").textContent =
        formatUSD(vessel.est_annual_flow_usd || 0);

    // Risk breakdown bar
    const sanctions = vessel.gfw_match !== false ? 40 : 40;
    const identity = Math.min((vessel.identity_changes || 0) * 10, 30);
    const encounters = Math.min((vessel.encounters || 0) * 5, 30);
    const total = sanctions + identity + encounters;

    document.getElementById("bar-sanctions").style.width = (sanctions / 100 * 100) + "%";
    document.getElementById("bar-identity").style.width = (identity / 100 * 100) + "%";
    document.getElementById("bar-encounters").style.width = (encounters / 100 * 100) + "%";

    // Pan map to vessel
    if (vessel._lat && vessel._lng) {
        map.flyTo([vessel._lat, vessel._lng], 6, { duration: 1.5 });
    }
}

// ── Vessel List ─────────────────────────────────────────────

function renderVesselList(filter = "") {
    const container = document.getElementById("vessel-list");
    container.innerHTML = "";

    const filtered = allVessels
        .filter(v => {
            if (!filter) return true;
            const q = filter.toLowerCase();
            return (v.name || "").toLowerCase().includes(q) ||
                   (v.imo || "").toLowerCase().includes(q);
        })
        .sort((a, b) => b.risk_score - a.risk_score);

    filtered.forEach(vessel => {
        const row = document.createElement("div");
        row.className = "vessel-row";
        row.onclick = () => showVesselDetail(vessel);

        const rc = riskClass(vessel.risk_score);
        const statusClass = vessel.cargo_status || "UNKNOWN";

        row.innerHTML = `
            <div class="vessel-row-risk ${rc}" style="border-color: ${riskColor(vessel.risk_score)}; color: ${riskColor(vessel.risk_score)}">
                ${vessel.risk_score}
            </div>
            <div class="vessel-row-info">
                <div class="vessel-row-name">${vessel.name || "UNKNOWN"}</div>
                <div class="vessel-row-meta">IMO ${vessel.imo} · ${formatUSD(vessel.est_cargo_value_usd || 0)}</div>
            </div>
            <div class="vessel-row-cargo ${statusClass}">${statusClass}</div>
        `;
        container.appendChild(row);
    });
}

