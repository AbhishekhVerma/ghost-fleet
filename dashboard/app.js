// Simulated vessel positions (for demo without live AIS feed).
// In production this would come from AIS/GFW position API.
// These are realistic coordinates in known shadow-fleet corridors.
function generateDemoPositions(count) {
    const corridors = [
        // Black Sea / Kerch area
        { latMin: 43, latMax: 46, lngMin: 32, lngMax: 40, weight: 0.3 },
        // Mediterranean / Laconian Gulf
        { latMin: 34, latMax: 38, lngMin: 18, lngMax: 28, weight: 0.25 },
        // Indian Ocean / Arabian Sea
        { latMin: 10, latMax: 25, lngMin: 55, lngMax: 70, weight: 0.2 },
        // Southeast Asia / Malacca
        { latMin: -2, latMax: 8, lngMin: 98, lngMax: 108, weight: 0.15 },
        // West Africa
        { latMin: 0, latMax: 10, lngMin: -10, lngMax: 5, weight: 0.1 },
    ];

    const positions = [];
    for (let i = 0; i < count; i++) {
        // Pick corridor based on weight
        const r = Math.random();
        let cumWeight = 0;
        let corridor = corridors[0];
        for (const c of corridors) {
            cumWeight += c.weight;
            if (r <= cumWeight) { corridor = c; break; }
        }
        positions.push({
            lat: corridor.latMin + Math.random() * (corridor.latMax - corridor.latMin),
            lng: corridor.lngMin + Math.random() * (corridor.lngMax - corridor.lngMin),
        });
    }
    return positions;
}

// ── Utilities ───────────────────────────────────────────────

function formatUSD(value) {
    if (value >= 1_000_000_000) return "$" + (value / 1_000_000_000).toFixed(1) + "B";
    if (value >= 1_000_000) return "$" + (value / 1_000_000).toFixed(1) + "M";
    if (value >= 1_000) return "$" + (value / 1_000).toFixed(0) + "K";
    return "$" + value.toFixed(0);
}

function formatNumber(n) {
    return n != null ? n.toLocaleString() : "—";
}

function riskClass(score) {
    if (score >= 80) return "risk-critical";
    if (score >= 60) return "risk-high";
    if (score >= 40) return "risk-medium";
    return "risk-low";
}

function riskColor(score) {
    if (score >= 80) return "#ef4444";
    if (score >= 60) return "#f97316";
    if (score >= 40) return "#eab308";
    return "#22c55e";
}

